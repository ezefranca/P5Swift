/// Failures produced by native audio loading, analysis, and engine control.
public enum P5AudioError: Error, Sendable, Hashable, LocalizedError {
    /// AVFoundation could not open an audio file.
    case fileLoadingFailed(String)
    /// AVAudioEngine could not begin rendering.
    case engineStartFailed(String)
    /// A requested file-player timestamp is outside the file timeline.
    case invalidTime
    /// A PCM buffer does not expose finite Float32 samples.
    case invalidSamples
    /// Accelerate could not allocate the requested Fourier transform.
    case analyzerCreationFailed(String)
    /// AVFoundation could not create a mono oscillator stream format.
    case formatCreationFailed
    /// The engine already has an output analyzer tap.
    case analyzerAlreadyInstalled

    /// A localized description suitable for diagnostics and user interfaces.
    public var errorDescription: String? {
        switch self {
        case .fileLoadingFailed(let reason):
            "The audio file could not be loaded: \(reason)"
        case .engineStartFailed(let reason):
            "The native audio engine could not start: \(reason)"
        case .invalidTime:
            "Audio time must be finite, nonnegative, and within the file duration."
        case .invalidSamples:
            "Audio analysis requires finite Float32 PCM samples and a positive sample rate."
        case .analyzerCreationFailed(let reason):
            "The audio analyzer could not be created: \(reason)"
        case .formatCreationFailed:
            "AVFoundation could not create the oscillator audio format."
        case .analyzerAlreadyInstalled:
            "The audio engine already has an output analyzer installed."
        }
    }
}

/// Validated metadata for a local AVFoundation audio file.
public struct P5AudioFile: Sendable {
    /// Local source URL.
    public let url: URL
    /// File duration in seconds.
    public let duration: Double
    /// Native processing sample rate in hertz.
    public let sampleRate: Double
    /// Number of interleaved or noninterleaved audio channels.
    public let channelCount: Int

    /// Opens a local file and loads its native processing metadata.
    public init(url: URL) throws {
        try self.init(url: url, runtime: P5AudioFileRuntime())
    }

    init(url: URL, runtime: P5AudioFileRuntime) throws {
        do {
            let file = try runtime.open(url)
            let sampleRate = file.processingFormat.sampleRate
            let channelCount = Int(file.processingFormat.channelCount)
            let duration = Double(file.length) / sampleRate
            guard
                file.length > 0,
                sampleRate.isFinite && sampleRate > 0,
                channelCount > 0,
                duration.isFinite && duration >= 0
            else {
                throw P5AudioError.fileLoadingFailed(
                    "AVFoundation returned invalid file metadata."
                )
            }
            self.url = url
            self.duration = duration
            self.sampleRate = sampleRate
            self.channelCount = channelCount
        } catch let error as P5AudioError {
            throw error
        } catch {
            throw P5AudioError.fileLoadingFailed(error.localizedDescription)
        }
    }
}

