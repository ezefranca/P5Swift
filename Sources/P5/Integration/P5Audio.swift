struct P5AudioEngineRuntime: @unchecked Sendable {
    var prepare: (AVAudioEngine) -> Void = { $0.prepare() }
    var start: (AVAudioEngine) throws -> Void = { try $0.start() }
    var pause: (AVAudioEngine) -> Void = { $0.pause() }
    var stop: (AVAudioEngine) -> Void = { $0.stop() }
    var reset: (AVAudioEngine) -> Void = { $0.reset() }
    var outputVolume: (AVAudioMixerNode) -> Float = { $0.outputVolume }
    var setOutputVolume: (AVAudioMixerNode, Float) -> Void = { $0.outputVolume = $1 }
    var outputFormat: (AVAudioMixerNode) -> AVAudioFormat = { $0.outputFormat(forBus: 0) }
    var makeFormat: (Double) -> AVAudioFormat? = {
        AVAudioFormat(standardFormatWithSampleRate: $0, channels: 1)
    }
    var makeSourceNode:
        (
            AVAudioFormat,
            @escaping @Sendable (AVAudioFrameCount, UnsafeMutableAudioBufferListPointer) -> Void
        ) ->
            AVAudioSourceNode = { format, render in
                AVAudioSourceNode(format: format) { _, _, frameCount, audioBufferList in
                    render(frameCount, UnsafeMutableAudioBufferListPointer(audioBufferList))
                    return noErr
                }
            }
    var makePlayerNode: () -> AVAudioPlayerNode = AVAudioPlayerNode.init
    var openFile: (URL) throws -> AVAudioFile = { try AVAudioFile(forReading: $0) }
    var attach: (AVAudioEngine, AVAudioNode) -> Void = { $0.attach($1) }
    var connect: (AVAudioEngine, AVAudioNode, AVAudioNode, AVAudioFormat?) -> Void = {
        $0.connect($1, to: $2, format: $3)
    }
    var installTap:
        (AVAudioMixerNode, AVAudioFrameCount, @escaping @Sendable (AVAudioPCMBuffer) -> Void) ->
            Void = {
                node, size, process in
                node.installTap(
                    onBus: 0,
                    bufferSize: size,
                    format: nil,
                    block: Self.tapHandler(process)
                )
            }
    var removeTap: (AVAudioMixerNode) -> Void = { $0.removeTap(onBus: 0) }

    static func tapHandler(
        _ process: @escaping @Sendable (AVAudioPCMBuffer) -> Void
    ) -> @Sendable (AVAudioPCMBuffer, AVAudioTime) -> Void {
        { buffer, _ in process(buffer) }
    }
}

