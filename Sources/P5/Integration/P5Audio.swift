final class P5AudioEngineCleanup: @unchecked Sendable {
    private let engine: AVAudioEngine
    private let runtime: P5AudioEngineRuntime
    private let lock = NSLock()
    private var tapInstalled = false

    init(engine: AVAudioEngine, runtime: P5AudioEngineRuntime) {
        self.engine = engine
        self.runtime = runtime
    }

    func setTapInstalled(_ installed: Bool) {
        lock.withLock { tapInstalled = installed }
    }

    deinit {
        if lock.withLock({ tapInstalled }) {
            runtime.removeTap(engine.mainMixerNode)
        }
        runtime.stop(engine)
    }
}
